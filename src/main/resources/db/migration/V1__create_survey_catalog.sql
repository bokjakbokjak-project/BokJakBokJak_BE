-- 설문 카탈로그: 카테고리 > 비교 주제 > 문항(내 습관 / 상대 허용범위) > 선택지

CREATE TABLE survey_category (
    code          VARCHAR(40) PRIMARY KEY,
    name          VARCHAR(40) NOT NULL,
    display_order SMALLINT    NOT NULL UNIQUE
);

CREATE TABLE survey_topic (
    code          VARCHAR(40)  PRIMARY KEY,
    category_code VARCHAR(40)  NOT NULL REFERENCES survey_category (code),
    scenario_text VARCHAR(300) NOT NULL,
    display_order SMALLINT     NOT NULL UNIQUE
);

CREATE TABLE question (
    code            VARCHAR(50)  PRIMARY KEY,
    topic_code      VARCHAR(40)  NOT NULL REFERENCES survey_topic (code),
    kind            VARCHAR(16)  NOT NULL CHECK (kind IN ('HABIT', 'TOLERANCE')),
    question_number SMALLINT     NOT NULL UNIQUE,
    prompt          VARCHAR(300) NOT NULL,
    UNIQUE (topic_code, kind)
);

CREATE TABLE question_option (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_code VARCHAR(50)  NOT NULL REFERENCES question (code),
    code          VARCHAR(50)  NOT NULL,
    label         VARCHAR(100) NOT NULL,
    display_order SMALLINT     NOT NULL,
    UNIQUE (question_code, code),
    UNIQUE (question_code, display_order)
);
