-- 회원(설문에 필요한 최소 컬럼)과 설문 답변·카테고리 순위
-- 학교·이메일·Google 식별자 등은 로그인 기능에서 컬럼을 추가한다

CREATE TABLE app_user (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    onboarding_completed_at TIMESTAMP WITH TIME ZONE,
    survey_revision         INTEGER                  NOT NULL DEFAULT 0,
    survey_completed_at     TIMESTAMP WITH TIME ZONE,
    created_at              TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at              TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE user_weight (
    user_id       BIGINT      NOT NULL REFERENCES app_user (id),
    category_code VARCHAR(40) NOT NULL REFERENCES survey_category (code),
    priority_rank SMALLINT    NOT NULL,
    PRIMARY KEY (user_id, category_code),
    UNIQUE (user_id, priority_rank)
);

CREATE TABLE survey_answer (
    user_id       BIGINT      NOT NULL REFERENCES app_user (id),
    question_code VARCHAR(50) NOT NULL REFERENCES question (code),
    option_code   VARCHAR(50) NOT NULL,
    PRIMARY KEY (user_id, question_code),
    FOREIGN KEY (question_code, option_code) REFERENCES question_option (question_code, code)
);
