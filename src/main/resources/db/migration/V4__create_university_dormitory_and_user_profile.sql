-- 학교·기숙사 방 타입과 회원 프로필(온보딩 정보·상태)
-- Google 식별자·이메일은 로그인 기능에서 컬럼을 추가한다

CREATE TABLE university (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code   VARCHAR(40) NOT NULL UNIQUE,
    name   VARCHAR(60) NOT NULL,
    active BOOLEAN     NOT NULL DEFAULT TRUE
);

-- Google ID 토큰의 hd 또는 이메일 도메인 중 하나라도 일치하면 해당 학교로 본다
CREATE TABLE university_domain (
    domain        VARCHAR(100) PRIMARY KEY,
    university_id BIGINT       NOT NULL REFERENCES university (id)
);

CREATE TABLE dormitory_room_type (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    university_id  BIGINT      NOT NULL REFERENCES university (id),
    dormitory_key  VARCHAR(80) NOT NULL,
    dormitory_name VARCHAR(80) NOT NULL,
    name           VARCHAR(40) NOT NULL,
    capacity       SMALLINT    NOT NULL CHECK (capacity > 0),
    UNIQUE (university_id, dormitory_key, name)
);

